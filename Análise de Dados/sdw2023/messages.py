import random
from time import sleep


def obter_noticia_dinamica(row):
    sleep(0.1)
    nome = row["nome"].split()[0]
    tipo = row["tipo_cartao"]
    limite = row["limite_cartao"]

    if "Black" in tipo or "Infinite" in tipo:
        categoria = "Black/Infinite"
    elif "Platinum" in tipo:
        categoria = "Platinum"
    elif limite >= 5000:
        categoria = "Limite_Alto"
    else:
        categoria = "Padrao"

    template = random.choice(MENSAGENS_POOL[categoria])

    return template.format(nome=nome)
